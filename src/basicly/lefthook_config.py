from __future__ import annotations

import json
import shlex
from collections import defaultdict
from dataclasses import dataclass
from io import StringIO
from pathlib import Path

import yaml
from ruamel.yaml import YAML

from . import hook_python, lefthook_artifacts
from .legacy_hooks import foreign_git_hook
from .projection import SyncResult, sync_file
from .scaffolds import UVX_COMMAND

CONFIG = "lefthook.yml"
MANAGED_CONFIG = ".basicly/lefthook.yml"
RUNTIME = "lefthook-runtime.py"
INTERPRETER = hook_python.COMMAND


@dataclass(frozen=True)
class HookSpec:
    id: str
    script: str
    stage: str
    pass_filenames: bool = False
    always_run: bool = False
    files: str = ""
    manager: str = "git"
    technologies: tuple[str, ...] = ()
    matcher: str = ""


def managed_config(specs: list[HookSpec], hooks_relpath: str, secret_exclude: str = "") -> str:
    groups: dict[str, list[dict]] = defaultdict(list)
    for spec in specs:
        name = spec.stage if spec.manager == "git" else f"basicly-{spec.manager}-{spec.stage}"
        entry = {
            "id": spec.id,
            "script": f"{hooks_relpath}/{spec.script}",
            "stage": spec.stage,
            "pass_filenames": spec.pass_filenames,
            "always_run": spec.always_run,
            "files": spec.files,
            "manager": spec.manager,
            "technologies": spec.technologies,
            "matcher": spec.matcher,
        }
        groups[name].append(entry)
    data: dict = {"min_version": lefthook_artifacts.VERSION}
    for name, entries in groups.items():
        data[name] = {
            "commands": {
                "basicly-dispatch": {
                    "run": f'{hook_python.DISPATCH_COMMAND} "{hooks_relpath}/{RUNTIME}" dispatch',
                    "use_stdin": entries[0]["manager"] != "git",
                    "env": {
                        **hook_python.ENVIRONMENT,
                        "BASICLY_HOOK_SPECS": json.dumps(entries),
                        **({"BASICLY_SECRET_EXCLUDE": secret_exclude} if secret_exclude else {}),
                        "BASICLY_FOLD_COMMAND": json.dumps([
                            *shlex.split(UVX_COMMAND),
                            "tracker",
                            "fold",
                        ]),
                    },
                }
            }
        }
        if entries[0]["manager"] == "git":
            data[name]["follow"] = True
    return "# Generated by basicly hooks-build. Do not edit manually.\n" + yaml.safe_dump(
        data, sort_keys=False
    )


def root_config(text: str, secret_exclude: str | None = None) -> str:
    parser = YAML()
    parser.preserve_quotes = True
    data = parser.load(text) if text.strip() else {}
    if not isinstance(data, dict):
        raise ValueError("lefthook.yml must contain a mapping")
    for name, hook in data.items():
        if isinstance(hook, dict) and "basicly-dispatch" in hook.get("commands", {}):
            override = hook["commands"]["basicly-dispatch"]
            if (
                name != "pre-commit"
                or not isinstance(override, dict)
                or set(override) != {"env"}
                or not isinstance(override["env"], dict)
                or set(override["env"]) != {"BASICLY_SECRET_EXCLUDE"}
                or not isinstance(override["env"]["BASICLY_SECRET_EXCLUDE"], str)
            ):
                raise ValueError(
                    f"consumer configuration overrides managed {name}/basicly-dispatch"
                )
    extends = data.get("extends", [])
    if not isinstance(extends, list):
        raise ValueError("lefthook.yml extends must be a list")
    changed = False
    if secret_exclude:
        env = (
            data
            .setdefault("pre-commit", {})
            .setdefault("commands", {})
            .setdefault("basicly-dispatch", {})
            .setdefault("env", {})
        )
        if "BASICLY_SECRET_EXCLUDE" not in env:
            env["BASICLY_SECRET_EXCLUDE"] = secret_exclude
            changed = True
    if MANAGED_CONFIG in extends and not changed:
        return text
    if MANAGED_CONFIG not in extends:
        data["extends"] = [*extends, MANAGED_CONFIG]
    output = StringIO()
    parser.dump(data, output)
    return output.getvalue()


def sync_config(
    repo_root: Path, specs: list[HookSpec], hooks_relpath: str, secret_exclude: str | None = None
) -> SyncResult:
    result = SyncResult()
    alternatives = [
        "lefthook.yaml",
        ".lefthook.yml",
        ".lefthook.yaml",
        "lefthook.toml",
        ".lefthook.toml",
        "lefthook.json",
        ".lefthook.json",
        "lefthook.jsonc",
        ".lefthook.jsonc",
        ".config/lefthook.yml",
        ".config/lefthook.yaml",
        ".config/lefthook.toml",
        ".config/lefthook.json",
        ".config/lefthook.jsonc",
    ]
    present = [name for name in alternatives if (repo_root / name).exists()]
    if present:
        raise ValueError(
            f"existing Lefthook configuration {present} needs consolidation into lefthook.yml; "
            "refusing to create competing configurations"
        )
    path = repo_root / CONFIG
    current = path.read_text(encoding="utf-8") if path.exists() else ""
    rendered = root_config(current, secret_exclude)
    if path.is_file() and rendered == current:
        result.unchanged.append(path)
    else:
        sync_file(path, rendered.encode(), result)
    sync_file(repo_root / MANAGED_CONFIG, managed_config(specs, hooks_relpath).encode(), result)
    return result


def config_mismatches(
    repo_root: Path, specs: list[HookSpec], hooks_relpath: str
) -> list[tuple[Path, str]]:
    found: list[tuple[Path, str]] = []
    root = repo_root / CONFIG
    current = root.read_text(encoding="utf-8") if root.exists() else ""
    if root_config(current) != current:
        found.append((root, "missing managed Lefthook configuration"))
    path = repo_root / MANAGED_CONFIG
    expected = managed_config(specs, hooks_relpath)
    if not path.exists() or path.read_text(encoding="utf-8") != expected:
        found.append((path, "managed Lefthook configuration out of sync"))
    return found


GIT_HOOK_MARKER = "basicly Lefthook launcher"


def render_git_launcher(stage: str, core_hooks_dir: Path, saved_body: bytes) -> bytes:
    runtime = (core_hooks_dir / "lefthook-runtime.py").as_posix()
    original = f"$(git rev-parse --git-path hooks)/{stage}.basicly-original"
    legacy = f"$(git rev-parse --git-path hooks)/{stage}.legacy"
    lines = [
        "#!/bin/sh",
        f"# {GIT_HOOK_MARKER}",
        f'basicly_original="{original}"',
        f'basicly_legacy="{legacy}"',
        f'if [ ! -f "{runtime}" ]; then',
        '  if [ -x "$basicly_original" ]; then',
        '    exec "$basicly_original" "$@"',
        "  fi",
        "  exit 0",
        "fi",
    ]
    if saved_body and b"# File generated by pre-commit" not in saved_body:
        suffix = "original" if foreign_git_hook(stage, saved_body) == saved_body else "foreign"
        lines.append(
            f'export BASICLY_FOREIGN_HOOK="$(git rev-parse --git-path hooks)/'
            f'{stage}.basicly-{suffix}"'
        )
    if b"# File generated by pre-commit" in saved_body:
        lines.extend([
            'if [ -x "$basicly_legacy" ]; then',
            '  export BASICLY_FOREIGN_HOOK="$basicly_legacy"',
            "fi",
        ])
    lines.append(f'exec {INTERPRETER} "{runtime}" git {stage} "$@"')
    return ("\n".join(lines) + "\n").encode("utf-8")
