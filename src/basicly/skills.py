"""Skill collection discovery and projection helpers.

Skills are authored as a non-discoverable ``skill.yaml`` source (name,
description, ``instructions`` block scalar, and optional Agent-Skills-spec
frontmatter) so a broadly-scanning agent never finds the catalog source as a
second ``SKILL.md`` (architecture §4.2). The projector renders the discoverable
``SKILL.md`` at the target roots only, so exactly one copy an agent can load
exists per skill.

A skill source directory may bundle the full Agent Skills layout
(https://agentskills.io/specification): ``scripts/``, ``references/``,
``assets/`` and any additional files or directories. Every bundled file — that
is, everything under the skill source dir except the ``skill.yaml`` source
itself — is copied verbatim (bytes and mode) alongside the rendered ``SKILL.md``
into each destination root, so a skill can carry a long reference guide or a
fixer script. The rendered ``SKILL.md`` carries the generated marker (a hand
edit is obviously wrong); the bundled resources are hand-authored and are copied
without a marker. The projected skill directory is a pure projection target
owned wholly by basicly, so it is *mirrored*: a resource dropped from the source
is pruned from the projection, and deselecting a skill's technology prunes the
whole directory.
"""

from __future__ import annotations

import shutil
from dataclasses import dataclass
from pathlib import Path

import yaml

from .projection import SyncResult, sync_file, write_if_changed
from .schema import ValidationError, technology_selected, validate_technologies

SKILLS_SOURCE_DIR = Path(".basicly/core/skills")
SKILL_SOURCE_FILE = "skill.yaml"
SKILL_FILE_NAME = "SKILL.md"

# The invocation axis (basicly-m4zv.1, catalog-efficacy-design §3.5).
MODEL_INVOKED = "model"
USER_INVOKED = "user"
INVOCATIONS = frozenset({MODEL_INVOKED, USER_INVOKED})
# .claude/skills is Claude Code's only project root; .agents/skills is the
# Agent Skills open-standard root Codex reads. Copilot/VS Code reads BOTH (plus
# .github/skills), so a .github copy would only triple its discovery — it was
# dropped from the defaults (basicly-sqn) and is pruned as a retired root.
DEFAULT_SKILL_ROOTS = (
    Path(".claude/skills"),
    Path(".agents/skills"),
)
# Loader tolerance for a missing `description` differs by root (basicly-m4zv.10),
# so the render does too. Claude Code loads a description-less skill and still
# lists it by name — that tolerance is what makes the invocation axis's saving
# possible at all. Codex rejects the file outright ("missing field
# `description`"), so on the open-standard root the trade is not "pay tokens or
# save them" but "have the skill or not": v0.5.1 shipped these three loadable and
# main does not. Listed as tolerant rather than as requiring, so an unrecognised
# custom root fails safe toward a file that loads.
DESCRIPTION_OPTIONAL_ROOTS = frozenset({".claude/skills"})

# Roots basicly used to project into; generated-marker files here are pruned on
# skills-build/install and removed by uninstall.
RETIRED_SKILL_ROOTS = (Path(".github/skills"),)

# Marker injected into every rendered SKILL.md so a hand-edit of the projected
# (generated) copy is obviously wrong — the YAML source is the thing to edit.
GENERATED_MARKER = (
    "<!-- Generated by `basicly skills-build` from skill.yaml. Do not edit; edit the source. -->"
)

# Prefix of every mismatch reason a rebuild cannot clear, because no source
# describes the file. The check-side remedy keys on it to say so.
UNMANAGED_REASON_PREFIX = "unmanaged ("


@dataclass(frozen=True)
class SkillDefinition:
    """A source skill loaded from .basicly/core/skills.

    ``technologies`` is basicly-internal scoping (§9) and is NOT emitted into the
    projected SKILL.md frontmatter. The optional spec fields (``license``,
    ``compatibility``, ``allowed_tools``, ``metadata``) round-trip into the
    frontmatter; omitting them yields the minimal ``name``/``description`` header.
    """

    slug: str
    name: str
    # The invocation axis (basicly-m4zv.1). A model-invoked entry keeps a
    # description and is advertised to the agent, paying context load every turn;
    # a user-invoked entry carries none and is reached by a human typing it.
    # Declared rather than inferred, because "does this route correctly" is not a
    # well-posed question until an entry knows whether anything can route to it —
    # which is why this is the prerequisite for the Tier-2 routing evals.
    invocation: str
    # Empty for a user-invoked entry; the pairing is enforced by catalog_lint.
    description: str
    instructions: str
    source_path: Path
    technologies: tuple[str, ...] = ()
    license: str | None = None
    compatibility: str | None = None
    allowed_tools: str | None = None
    metadata: tuple[tuple[str, str], ...] = ()

    @property
    def source_dir(self) -> Path:
        """The skill's source directory (parent of ``skill.yaml``)."""
        return self.source_path.parent


def _require_str(value: object, field: str, path: Path) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValidationError(f"missing required field '{field}'", path)
    return value


def _optional_str(
    value: object, field: str, path: Path, *, max_len: int | None = None
) -> str | None:
    """Validate an optional spec string field (absent -> None)."""
    if value is None:
        return None
    if not isinstance(value, str) or not value.strip():
        raise ValidationError(f"field '{field}' must be a non-empty string", path)
    if max_len is not None and len(value) > max_len:
        raise ValidationError(f"field '{field}' exceeds {max_len} characters", path)
    return value


def _load_metadata(value: object, path: Path) -> tuple[tuple[str, str], ...]:
    """Validate the optional ``metadata`` map (string keys -> string values)."""
    if value is None:
        return ()
    if not isinstance(value, dict):
        raise ValidationError("field 'metadata' must be a mapping", path)
    items: list[tuple[str, str]] = []
    for key, entry in value.items():
        if not isinstance(key, str):
            raise ValidationError("metadata keys must be strings", path)
        if not isinstance(entry, str):
            raise ValidationError(
                f"metadata value for '{key}' must be a string (quote numbers, e.g. \"1.0\")", path
            )
        items.append((key, entry))
    return tuple(items)


def discover_skills(
    repo_root: Path,
    source_dir: Path = SKILLS_SOURCE_DIR,
) -> list[SkillDefinition]:
    """Load and validate all skills from the source collection directory."""
    base_dir = repo_root / source_dir
    if not base_dir.exists():
        return []

    skills: list[SkillDefinition] = []
    seen_slugs: set[str] = set()

    for path in sorted(base_dir.glob(f"*/{SKILL_SOURCE_FILE}")):
        slug = path.parent.name
        if slug in seen_slugs:
            raise ValidationError(f"duplicate skill slug '{slug}'", path)
        seen_slugs.add(slug)

        try:
            data = yaml.safe_load(path.read_text(encoding="utf-8"))
        except yaml.YAMLError as exc:
            raise ValidationError(f"invalid YAML: {exc}", path) from exc
        if not isinstance(data, dict):
            raise ValidationError("skill source must be a YAML mapping", path)

        technologies = validate_technologies(data.get("technologies") or [], path)

        invocation = _require_str(data.get("invocation"), "invocation", path).strip()
        if invocation not in INVOCATIONS:
            raise ValidationError(
                f"field 'invocation' must be one of {', '.join(sorted(INVOCATIONS))}, "
                f"got {invocation!r}",
                path,
            )
        # A user-invoked entry legitimately has no description, so this cannot go
        # through _require_str. The pairing (model needs one, user must not have
        # one) is a catalog_lint rule so the failure can explain itself.
        raw_description = data.get("description")
        description = raw_description.strip() if isinstance(raw_description, str) else ""

        skills.append(
            SkillDefinition(
                slug=slug,
                name=_require_str(data.get("name"), "name", path).strip(),
                invocation=invocation,
                description=description,
                instructions=_require_str(data.get("instructions"), "instructions", path),
                source_path=path,
                technologies=tuple(technologies),
                license=_optional_str(data.get("license"), "license", path),
                compatibility=_optional_str(
                    data.get("compatibility"), "compatibility", path, max_len=500
                ),
                allowed_tools=_optional_str(data.get("allowed-tools"), "allowed-tools", path),
                metadata=_load_metadata(data.get("metadata"), path),
            )
        )

    return skills


def _optional_frontmatter(skill: SkillDefinition) -> str:
    """Render the optional spec frontmatter block (empty when none is set)."""
    fields: dict[str, object] = {}
    if skill.license is not None:
        fields["license"] = skill.license
    if skill.compatibility is not None:
        fields["compatibility"] = skill.compatibility
    if skill.allowed_tools is not None:
        fields["allowed-tools"] = skill.allowed_tools
    if skill.metadata:
        fields["metadata"] = dict(skill.metadata)
    if not fields:
        return ""
    return yaml.safe_dump(fields, sort_keys=False, allow_unicode=True, default_flow_style=False)


def render_skill_md(skill: SkillDefinition, *, require_description: bool = False) -> str:
    """Render the discoverable SKILL.md (frontmatter + generated marker + body).

    ``name`` and ``description`` are emitted verbatim (byte-identical to the
    pre-spec minimal header); any optional spec fields follow as a YAML block.

    A **user-invoked** entry emits no ``description`` line at all, which is the
    whole mechanism: the description is what the agent reads to decide whether to
    route here, and an entry nothing can route to should not be paying for one
    every turn.

    Measured 2026-07-26, and worth stating because the design overstates it: on
    Claude Code a description-less skill still *loads* and is still listed by
    name, so the model can still invoke it. Stripping the description removes
    ~95% of this repo's skill-index text (6113 of 6412 chars) but not the name —
    so "user-invoked" delivers a large context saving, not zero context load and
    not human-only reach.

    **That tolerance is Claude's, not universal (basicly-m4zv.10).** Codex rejects
    a description-less file outright — ``missing field `description` `` — so the
    stripping that saves context on one root deletes the skill on another, which
    is why *require_description* exists and why the caller derives it from the
    destination root rather than choosing it. Since a user-invoked source carries
    no description (catalog lint forbids one), there is nothing to project for a
    root that demands the field and one is synthesized: the entry's name plus its
    contract, which satisfies the loader for a few tokens instead of restoring a
    routing description nothing should route to. Verified against codex-cli
    0.146.0 — three load failures before, zero after.

    **Where the marker goes depends on the axis (basicly-m4zv.7).** The host does
    not leave an absent description empty — it falls back to the first body line.
    With the marker sitting there, a user-invoked entry advertised
    ``<!-- Generated by basicly skills-build ... -->``: a string that tells the
    agent nothing while still costing tokens, a worse trade per character than the
    description it replaced. So a user-invoked entry carries the marker as a YAML
    comment inside the frontmatter, leaving its own first heading as the fallback.
    A model-invoked entry is untouched and stays byte-identical, its description
    already occupying that slot. Both forms keep the literal marker text in the
    file, which is what :func:`_is_generated_skill` matches on.
    """
    user_invoked = skill.invocation != MODEL_INVOKED
    # *require_description* is the root's loader tolerance, not a style choice
    # (basicly-m4zv.10). A user-invoked source carries no description by design —
    # catalog lint forbids one — so for a root that demands the field there is
    # nothing to project and it must be synthesized. Name the entry and state its
    # contract rather than writing a routing description: the field satisfies the
    # loader for a few tokens without advertising a route no human wants taken.
    stripped = user_invoked and not require_description
    if user_invoked and require_description:
        text = f"User-invoked skill {skill.name}. A human runs it by name."
    else:
        text = skill.description
    description = "" if stripped else f"description: {text}\n"
    marker_comment = f"# {GENERATED_MARKER}\n" if stripped else ""
    body_marker = "" if stripped else f"{GENERATED_MARKER}\n\n"
    header = (
        f"---\nname: {skill.name}\n{marker_comment}{description}{_optional_frontmatter(skill)}---\n"
    )
    return f"{header}{body_marker}{skill.instructions}"


def resolve_skill_roots(
    repo_root: Path,
    roots: list[str] | None,
    use_default_roots: bool,
) -> list[Path]:
    """Resolve output roots for projected skills."""
    if roots:
        candidates = [Path(item) for item in roots]
    elif use_default_roots:
        candidates = list(DEFAULT_SKILL_ROOTS)
    else:
        # Keep default behavior minimal for this repo, but allow expansion with --all-default-roots.
        candidates = [DEFAULT_SKILL_ROOTS[0]]

    resolved: list[Path] = []
    seen: set[str] = set()

    for root in candidates:
        absolute_root = root if root.is_absolute() else repo_root / root
        key = str(absolute_root)
        if key in seen:
            continue
        seen.add(key)
        resolved.append(absolute_root)

    return resolved


def root_requires_description(skill_root: Path) -> bool:
    """Whether a skill projected under *skill_root* must carry a description.

    Keyed on the root's own last two path parts and joined with ``/`` so the
    comparison is identical on POSIX and Windows and works for an absolute root
    (``/repo/.claude/skills``) as well as a relative one. An unrecognised root
    requires a description: emitting one costs a few tokens, omitting one can
    cost the whole skill.
    """
    key = "/".join(skill_root.parts[-2:])
    return key not in DESCRIPTION_OPTIONAL_ROOTS


def _is_generated_skill(path: Path) -> bool:
    return path.is_file() and GENERATED_MARKER in path.read_text(encoding="utf-8", errors="ignore")


def _resource_files(skill: SkillDefinition) -> list[Path]:
    """Relative paths of every bundled file (everything but the skill.yaml source).

    A stray top-level ``SKILL.md`` in the source is skipped so it can never
    clobber the rendered one (catalog-lint also rejects it as a source).
    """
    src_dir = skill.source_dir
    files: list[Path] = []
    for candidate in sorted(src_dir.rglob("*")):
        if not candidate.is_file():
            continue
        rel = candidate.relative_to(src_dir)
        if rel == Path(SKILL_SOURCE_FILE) or rel == Path(SKILL_FILE_NAME):
            continue
        files.append(rel)
    return files


def _sync_resource(source: Path, target: Path, result: SyncResult) -> None:
    """Copy a bundled resource verbatim (bytes + mode) if it changed."""
    content = source.read_bytes()
    if write_if_changed(target, content):
        shutil.copymode(source, target)
        result.written.append(target)
    else:
        result.unchanged.append(target)


def _prune_orphans(skill_dir: Path, expected: set[Path]) -> list[Path]:
    """Remove projected files no longer in the source, then any emptied dirs."""
    if not skill_dir.is_dir():
        return []
    pruned: list[Path] = []
    for candidate in sorted(skill_dir.rglob("*"), reverse=True):
        if candidate.is_file() and candidate not in expected:
            candidate.unlink()
            pruned.append(candidate)
        elif candidate.is_dir() and not any(candidate.iterdir()):
            candidate.rmdir()
    return pruned


def _project_skill(skill: SkillDefinition, skill_dir: Path, result: SyncResult) -> list[Path]:
    """Mirror the source skill dir into ``skill_dir``; return files pruned as orphans."""
    expected: set[Path] = set()

    skill_md = skill_dir / SKILL_FILE_NAME
    require = root_requires_description(skill_dir.parent)
    sync_file(skill_md, render_skill_md(skill, require_description=require).encode("utf-8"), result)
    expected.add(skill_md)

    for rel in _resource_files(skill):
        target = skill_dir / rel
        _sync_resource(skill.source_dir / rel, target, result)
        expected.add(target)

    return _prune_orphans(skill_dir, expected)


def _prune_skill_dir(skill_dir: Path) -> list[Path]:
    """Delete a whole projected skill dir when it is basicly-owned (marker present)."""
    if not _is_generated_skill(skill_dir / SKILL_FILE_NAME):
        return []
    pruned = sorted(p for p in skill_dir.rglob("*") if p.is_file())
    shutil.rmtree(skill_dir)
    return pruned


def sync_skills(
    repo_root: Path,
    roots: list[Path],
    source_dir: Path = SKILLS_SOURCE_DIR,
    selection: frozenset[str] | None = None,
) -> tuple[SyncResult, list[Path]]:
    """Project selected source skills (SKILL.md + bundled resources) into each root.

    The projected skill directory is mirrored, so a resource removed from the
    source is pruned; a skill the technology *selection* now excludes has its
    whole projected directory pruned (basicly-owned dirs only, detected by the
    generated marker on SKILL.md). Returns the sync result plus the pruned paths.
    """
    skills = discover_skills(repo_root, source_dir)
    result = SyncResult()
    pruned: list[Path] = []

    for skill in skills:
        selected = technology_selected(skill.technologies, selection)
        for root in roots:
            skill_dir = root / skill.slug
            if selected:
                pruned.extend(_project_skill(skill, skill_dir, result))
            else:
                pruned.extend(_prune_skill_dir(skill_dir))

    return result, pruned


def _unmanaged_entries(
    root: Path, known_slugs: set[str], source_dir: Path
) -> list[tuple[Path, str]]:
    """Report entries under a projected root that no catalog source accounts for.

    The per-skill mirror (:func:`_check_projected_skill`) only ever visits
    directories a source names, so a hand-authored skill dropped into a projected
    root was invisible to every gate: it shipped to one agent and not the other,
    and nothing said so (basicly-tcmy.8). The root is a projection target owned
    wholly by basicly (architecture §4.2), so anything here without a source is a
    finding — either a hand-authored skill that belongs in the catalog, or a
    projection left behind by a source that was deleted.

    Reported, never pruned: `skills-build` mirrors *within* a skill directory it
    owns, and deleting a file no source describes would destroy the only copy.
    """
    if not root.is_dir():
        return []
    mismatches: list[tuple[Path, str]] = []
    for entry in sorted(root.iterdir()):
        if entry.is_file():
            reason = f"{UNMANAGED_REASON_PREFIX}a projected skills root holds skill dirs only)"
            mismatches.append((entry, reason))
            continue
        if not entry.is_dir() or entry.name in known_slugs:
            continue
        source = source_dir / entry.name / SKILL_SOURCE_FILE
        reason = f"{UNMANAGED_REASON_PREFIX}no skill source at {source.as_posix()})"
        mismatches.extend((path, reason) for path in sorted(entry.rglob("*")) if path.is_file())
    return mismatches


def check_synced_skills(
    repo_root: Path,
    roots: list[Path],
    source_dir: Path = SKILLS_SOURCE_DIR,
    selection: frozenset[str] | None = None,
) -> list[tuple[Path, str]]:
    """Return missing, stale, orphaned, or unmanaged skill files for the selected roots."""
    skills = discover_skills(repo_root, source_dir)
    mismatches: list[tuple[Path, str]] = []

    for skill in skills:
        selected = technology_selected(skill.technologies, selection)
        for root in roots:
            skill_dir = root / skill.slug
            if not selected:
                skill_md = skill_dir / SKILL_FILE_NAME
                if _is_generated_skill(skill_md):
                    mismatches.append((skill_md, "excluded by technology selection"))
                continue
            mismatches.extend(_check_projected_skill(skill, skill_dir))

    # A deselected skill still has a source, so it stays out of the unmanaged
    # scan and keeps the targeted "excluded by technology selection" reason above.
    known_slugs = {skill.slug for skill in skills}
    for root in roots:
        mismatches.extend(_unmanaged_entries(root, known_slugs, source_dir))

    return mismatches


def _check_projected_skill(skill: SkillDefinition, skill_dir: Path) -> list[tuple[Path, str]]:
    """Compare one projected skill dir against its source (SKILL.md + resources + orphans)."""
    mismatches: list[tuple[Path, str]] = []
    expected: set[Path] = set()

    skill_md = skill_dir / SKILL_FILE_NAME
    expected.add(skill_md)
    require = root_requires_description(skill_dir.parent)
    rendered = render_skill_md(skill, require_description=require).encode("utf-8")
    if not skill_md.exists():
        mismatches.append((skill_md, "missing"))
    elif skill_md.read_bytes() != rendered:
        mismatches.append((skill_md, "content mismatch"))

    for rel in _resource_files(skill):
        target = skill_dir / rel
        expected.add(target)
        content = (skill.source_dir / rel).read_bytes()
        if not target.exists():
            mismatches.append((target, "missing"))
        elif target.read_bytes() != content:
            mismatches.append((target, "content mismatch"))

    if skill_dir.is_dir():
        for candidate in sorted(skill_dir.rglob("*")):
            if candidate.is_file() and candidate not in expected:
                mismatches.append((candidate, "unexpected (not in source)"))

    return mismatches
